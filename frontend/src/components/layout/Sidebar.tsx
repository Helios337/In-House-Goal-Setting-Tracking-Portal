"use client";

import * as React from "react";
import Link from "next/link";
import { usePathname } from "next/navigation";
import { useSession } from "next-auth/react";
import { cn } from "@/lib/utils";

type NavItem = { label: string; href: string; roles: string[]; icon: React.ReactNode };

const navLinks: NavItem[] = [
  // Employee Links
  { label: "My Goals", href: "/goals", roles: ["Employee", "Manager (L1)", "Admin / HR"], icon: <GoalIcon /> },
  { label: "My Check-ins", href: "/checkins", roles: ["Employee", "Manager (L1)", "Admin / HR"], icon: <CheckinIcon /> },
  
  // Manager Links
  { label: "Team Approvals", href: "/manager/approvals", roles: ["Manager (L1)", "Admin / HR"], icon: <InboxIcon /> },
  { label: "Team Dashboard", href: "/manager/dashboard", roles: ["Manager (L1)", "Admin / HR"], icon: <UsersIcon /> },
  
  // Admin / HR Links
  { label: "Completion Reports", href: "/admin/reports", roles: ["Admin / HR"], icon: <ChartIcon /> },
  { label: "Cycle Settings", href: "/admin/settings", roles: ["Admin / HR"], icon: <SettingsIcon /> },
];

export function Sidebar() {
  const pathname = usePathname();
  const { data: session } = useSession();
  const userRoles = session?.user?.roles || ["Employee"];

  // Filter links based on user roles
  const authorizedLinks = navLinks.filter(link => 
    link.roles.some(role => userRoles.includes(role))
  );

  return (
    <aside className="w-64 bg-slate-900 text-slate-300 min-h-screen flex flex-col hidden md:flex">
      <div className="p-6">
        <h1 className="text-white font-bold text-xl tracking-wide">AtomQuest</h1>
        <p className="text-xs text-slate-400 mt-1">Goal Tracking Portal</p>
      </div>
      
      <nav className="flex-1 px-4 space-y-1">
        {authorizedLinks.map((link) => {
          const isActive = pathname.startsWith(link.href);
          return (
            <Link
              key={link.href}
              href={link.href}
              className={cn(
                "flex items-center gap-3 px-3 py-2.5 rounded-md text-sm font-medium transition-colors",
                isActive 
                  ? "bg-blue-600 text-white" 
                  : "hover:bg-slate-800 hover:text-white"
              )}
            >
              {link.icon}
              {link.label}
            </Link>
          );
        })}
      </nav>
    </aside>
  );
}

